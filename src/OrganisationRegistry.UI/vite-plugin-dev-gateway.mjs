// Vite plugin that turns the dev/preview server into a small local gateway:
//  - aliases:       alias domains answered by the dev server, e.g. a redirect for an OAuth callback host;
//  - hosts:         extra host names accepted by the server; each one gets a throwaway certificate (SNI,
//                   in memory only, gone when the server stops), the server's own https option stays the default;
//  - proxy / mounts: put other apps under a path of this origin (proxy in dev, static directory in preview);
//  - runtimeConfig: serves /config.js built from the environment;
//  - httpPort:      plain-HTTP twin of the server, for tunnels that terminate TLS.
//
//   devGateway({
//     aliases: [{ host: "oauth.example.com", path: "/callback", redirect: "https://app.example.com/#/oic" }],
//     hosts: ["app.example.com"],
//     proxy: { "/v2": { target: "https://localhost:8443", secure: false, ws: true } },
//     mounts: { "/v2": "/abs/path/to/dist" },
//     runtimeConfig: { apiEndpoint: "API_ENDPOINT", version: (env) => `v2-${env.API_VERSION ?? ""}` },
//     httpPort: 9007,
//   })
import { execFileSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, statSync } from "node:fs";
import { createServer } from "node:http";
import { tmpdir } from "node:os";
import { extname, join, normalize } from "node:path";
import { createSecureContext } from "node:tls";

// Self-signed, valid for a day, never kept on disk (needs openssl on the PATH).
const throwawayContext = (host) => {
  const dir = mkdtempSync(join(tmpdir(), "dev-gateway-"));
  try {
    const key = join(dir, "k.pem");
    const cert = join(dir, "c.pem");
    execFileSync(
      "openssl",
      ["req", "-x509", "-newkey", "rsa:2048", "-nodes", "-days", "1", "-subj", `/CN=${host}`,
        "-addext", `subjectAltName=DNS:${host}`, "-keyout", key, "-out", cert],
      { stdio: "ignore" },
    );
    return createSecureContext({ key: readFileSync(key), cert: readFileSync(cert) });
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
};

const mime = {
  ".html": "text/html", ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css",
  ".json": "application/json", ".map": "application/json", ".svg": "image/svg+xml", ".png": "image/png",
  ".jpg": "image/jpeg", ".gif": "image/gif", ".ico": "image/x-icon", ".woff": "font/woff",
  ".woff2": "font/woff2", ".ttf": "font/ttf", ".eot": "application/vnd.ms-fontobject",
};

// Static mount with an index.html fallback (single page app), like nginx try_files.
const serveMount = (prefix, dir, path, res) => {
  const rel = normalize(path.slice(prefix.length) || "/").replace(/^([/\\]*\.\.)+/, "");
  let file = join(dir, rel);
  if (!file.startsWith(dir) || !existsSync(file) || statSync(file).isDirectory()) file = join(dir, "index.html");
  if (!existsSync(file)) {
    res.statusCode = 404;
    return res.end(`${prefix}: nothing built in ${dir}`);
  }
  res.setHeader("Content-Type", mime[extname(file)] ?? "application/octet-stream");
  res.setHeader("Cache-Control", "no-store");
  res.end(readFileSync(file));
};

export const devGateway = ({ aliases = [], hosts = [], proxy, mounts = {}, runtimeConfig, httpPort } = {}) => {
  const allHosts = [...new Set([...aliases.map((a) => a.host), ...hosts])];
  const cache = new Map();

  const configJs = () =>
    "// Runtime configuration generated by vite-plugin-dev-gateway\n" +
    Object.entries(runtimeConfig)
      .map(([key, source]) => {
        const value = typeof source === "function" ? source(process.env) : (process.env[source] ?? "");
        return `window.${key}=${JSON.stringify(value)};\n`;
      })
      .join("");

  const handler = (withMounts) => (req, res, next) => {
    const host = (req.headers.host ?? req.headers[":authority"] ?? "").split(":")[0]; // h2 has :authority
    const [path, query] = (req.url ?? "/").split("?");

    const alias = aliases.find((a) => a.host === host && (a.path === undefined || a.path === path));
    if (alias) {
      res.statusCode = 302;
      res.setHeader("Location", alias.redirect + (query ? `?${query}` : ""));
      return res.end();
    }
    if (aliases.some((a) => a.host === host)) {
      res.statusCode = 404; // an alias host only answers what is configured for it
      return res.end();
    }
    if (runtimeConfig && path === "/config.js") {
      res.setHeader("Content-Type", "application/javascript");
      res.setHeader("Cache-Control", "no-store");
      return res.end(configJs());
    }
    if (withMounts) {
      const prefix = Object.keys(mounts).find((p) => path === p || path.startsWith(p + "/"));
      if (prefix) return serveMount(prefix, mounts[prefix], path, res);
    }
    next();
  };

  const plain = (server) => {
    if (!httpPort) return;
    const hostname = process.env.HTTP_HOST || "127.0.0.1";
    const http = createServer(server.middlewares);
    http.on("error", (e) => server.config.logger.warn(`dev-gateway: plain HTTP port ${httpPort} not used (${e.code})`));
    http.listen(httpPort, hostname, () =>
      server.config.logger.info(`  ➜  dev-gateway: http://${hostname}:${httpPort}/ (no TLS, for tunnels)`));
    server.httpServer?.once("close", () => http.close());
  };

  return {
    name: "dev-gateway",
    config(config) {
      const withSni = (section) => {
        const https = section?.https;
        if (!https || !allHosts.length) return {};
        const main = section.host;
        return {
          https: {
            SNICallback(host, cb) {
              if (!host || host === main || !allHosts.includes(host)) return cb(null, undefined); // default context
              try {
                if (!cache.has(host)) cache.set(host, throwawayContext(host));
                cb(null, cache.get(host));
              } catch (e) {
                cb(e);
              }
            },
          },
        };
      };
      return {
        server: { allowedHosts: allHosts, proxy, ...withSni(config.server) },
        preview: { allowedHosts: allHosts, ...withSni(config.preview) },
      };
    },
    configureServer(server) {
      server.middlewares.use(handler(false));
      plain(server);
    },
    configurePreviewServer(server) {
      server.middlewares.use(handler(true));
      plain(server);
    },
  };
};
